# Lab 04 - Data Conversion Utility

print("========================================")
print("        DATA CONVERSION UTILITY         ")
print("========================================")
product_name = input("Enter Product Name : ")
price_input = input("Enter Price        : ")
quantity_input = input("Enter Quantity     : ")
price = float(price_input)
quantity = int(quantity_input)
total_price = price * quantity
amount_str = str(total_price)
print("\n----------------------------------------")
print("          TYPE CASTING SUMMARY          ")
print("----------------------------------------")
print(f"Variable\tValue\t\tPython Type")
print("-" * 47)
print(f"product_name\t{product_name}\t\t{type(product_name)}")
print(f"price\t\t{price}\t\t{type(price)}")
print(f"quantity\t{quantity}\t\t{type(quantity)}")
print(f"total_price\t{total_price}\t\t{type(total_price)}")
print(f"amount_str\t{amount_str}\t\t{type(amount_str)}")
print("\n----------------------------------------")
print("              TAX INVOICE               ")
print("----------------------------------------")
print(f"Product Name : {product_name}")
print(f"Price per Unit : Rs. {price}")
print(f"Quantity     : {quantity}")
print("-" * 40)
print(f"Invoice Total : Rs. {amount_str}")
print("========================================")